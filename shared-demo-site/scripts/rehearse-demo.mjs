import assert from 'node:assert/strict';
const base = process.argv[2] || 'http://127.0.0.1:4176';
assert.ok(new URL(base).hostname === '127.0.0.1', 'Rehearsal only runs against loopback');
const checks=[];
const req=async(path,options={})=>{const r=await fetch(base+path,options);return {status:r.status,body:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};};
assert.equal((await req('/api/rooms',{method:'POST'})).status,403); checks.push('local creation code required');
const made=await req('/api/rooms',{method:'POST',headers:{'X-Demo-Code':'local-rehearsal'}});assert.equal(made.status,200); assert.ok(made.cookie); const {id,hostToken,guestToken}=made.body;
const url='/api/rooms/'+id;
assert.equal((await req(url)).status,401);
let host=await req(url,{headers:{Authorization:'Bearer '+hostToken}});assert.equal(host.body.role,'host');
let guest=await req(url,{headers:{Authorization:'Bearer '+guestToken}});assert.equal(guest.body.role,'guest');
assert.equal((await req(url,{headers:{Cookie:host.cookie}})).body.role,'host');
assert.equal((await req(url,{headers:{Cookie:guest.cookie}})).body.role,'guest'); checks.push('separate role cookies recover after reload');
let revision=host.body.revision;
const act=async(token,action,expect=200)=>{const r=await req(url,{method:'POST',headers:{Authorization:'Bearer '+token,'Content-Type':'application/json'},body:JSON.stringify({revision,action})});assert.equal(r.status,expect);if(r.status===200)revision=r.body.revision;return r;};
const offers=[1,2,3].map(n=>new Date(Date.now()+n*86400000).toISOString());
await act(hostToken,{type:'invite',participant:'Matthew · Mitarbeiter 1',topic:'Wareneingang',offers,targetLevel:2});
await act(guestToken,{type:'report',result:'passed',report:'Not allowed'},400); checks.push('guest cannot submit trainer report');
await act(guestToken,{type:'reject_offer',offer:offers[0]});
await act(guestToken,{type:'accept_offer',offer:offers[1]});
await act(hostToken,{type:'reschedule',offers:[offers[2]]});
await act(hostToken,{type:'start_early'},400);
await act(guestToken,{type:'accept_offer',offer:offers[2]});
await act(hostToken,{type:'start_early'});
await act(hostToken,{type:'report',result:'passed',report:'Demo: Übungen und Verständnis überprüft.'});
const done=await act(guestToken,{type:'confirm_participation'});
assert.equal(done.body.state.active.stage,'completed');
assert.equal(done.body.state.skillMatrix['Matthew · Mitarbeiter 1'].Wareneingang.level,2);
assert.equal(done.body.state.skillMatrix['Marko · Mitarbeiter 3'].Wareneingang.level,3);
checks.push('decline, accept, reschedule, reaccept, early start, report, acknowledgement and per-person skill');
for(const kind of ['employees','catalogue','matrix']) {const r=await fetch(base+'/api/sources/'+kind);assert.equal(r.status,200);assert.match(await r.text(),/synthetic/);} checks.push('separate cloud source CSVs');
assert.equal((await fetch(base+'/materials/index.html')).status,200);checks.push('preparation material folder available');
console.log(JSON.stringify({result:'passed',checks,googleConnectedAcceptance:false,mailSent:false,remotePushDelivered:false},null,2));
